//! `snakes` — многопользовательская «Змейка» с протоколом v2 и TUI.
//!
//! # Карта модулей
//!
//! - [`wire`] переводит protobuf-датаграммы в доменные сообщения и обратно.
//! - [`reliable`] ведёт ACK, повторы и окна дедупликации, не обращаясь к сокетам.
//! - [`rules`] рассчитывает движение и столкновения на поле-торе.
//! - [`node`] связывает протокол и правила: подключение, роли, снимки и смену ведущего.
//! - [`catalog`] объединяет анонсы локальной сети и сервера курса.
//! - [`net`] выполняет UDP-ввод-вывод и выносит DNS в отдельный поток.
//! - [`ui`] превращает клавиши в команды узла, а его состояние — в терминальный кадр.
//!
//! # Поток данных
//!
//! Главный цикл в `src/main.rs` передаёт пакеты в [`node::Node::on_datagram`],
//! а монотонное время — в [`node::Node::on_tick`]. Узел не выполняет ввод-вывод:
//! он накапливает исходящие датаграммы и события для интерфейса. Цикл забирает
//! их через `drain_*` и передаёт транспорту и TUI.
//!
//! Только MASTER рассчитывает ходы; остальные узлы показывают принятые снимки.
//! Сетевая роль и статус игрока независимы: наблюдатель тоже может вести игру
//! или быть заместителем. Правила проверяются юнит-тестами, а взаимодействие
//! нескольких узлов — симулятором с виртуальным временем в `tests/sim.rs`.

pub mod catalog;
pub mod net;
pub mod node;
pub mod reliable;
pub mod rules;
pub mod ui;
pub mod wire;
